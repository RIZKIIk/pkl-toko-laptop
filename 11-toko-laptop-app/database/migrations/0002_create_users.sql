-- Skema awal akun pengguna. Kolom password_hash diganti oleh migration 0003
-- agar materi session lokal dapat memakai password teks biasa secara eksplisit.
CREATE TABLE IF NOT EXISTS public.users (
    -- ID stabil untuk setiap akun, dibuat otomatis oleh PostgreSQL.
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Username unik dan tidak boleh kosong setelah spasi pinggir dihapus.
    username VARCHAR(100) NOT NULL UNIQUE
        CHECK (LENGTH(BTRIM(username)) > 0),
    -- Migration berikutnya mengganti kolom ini khusus untuk materi latihan lokal.
    password_hash TEXT NOT NULL,
    -- Waktu akun pertama kali dibuat.
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
