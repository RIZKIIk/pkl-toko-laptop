-- Tabel utama untuk inventaris laptop dan batasan nilai datanya.
CREATE TABLE IF NOT EXISTS public.laptops (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama VARCHAR(150) NOT NULL
        CHECK (LENGTH(BTRIM(nama)) > 0),
    merek VARCHAR(100) NOT NULL
        CHECK (LENGTH(BTRIM(merek)) > 0),
    -- Harga disimpan sebagai rupiah utuh, bukan angka desimal.
    harga BIGINT NOT NULL
        CHECK (harga >= 0),
    stok INTEGER NOT NULL
        CHECK (stok >= 0),
    -- Waktu pencatatan dikelola database saat insert.
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
