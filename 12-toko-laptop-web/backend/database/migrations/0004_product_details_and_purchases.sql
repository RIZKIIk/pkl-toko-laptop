CREATE TABLE IF NOT EXISTS public.purchases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    username VARCHAR(100) NOT NULL,
    laptop_id BIGINT REFERENCES public.laptops(id) ON DELETE SET NULL,
    laptop_name VARCHAR(150) NOT NULL,
    laptop_brand VARCHAR(100) NOT NULL,
    unit_price BIGINT NOT NULL CHECK (unit_price >= 0),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    total_price BIGINT NOT NULL CHECK (total_price >= 0),
    payment_method VARCHAR(24) NOT NULL
        CHECK (payment_method IN ('qris', 'cash', 'bank_transfer', 'debit_card')),
    payment_status VARCHAR(24) NOT NULL DEFAULT 'simulated_paid'
        CHECK (payment_status IN ('simulated_paid')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS purchases_user_id_idx ON public.purchases (user_id);
CREATE INDEX IF NOT EXISTS purchases_created_at_idx ON public.purchases (created_at DESC);
