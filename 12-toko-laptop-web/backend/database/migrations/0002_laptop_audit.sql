-- Preserve the log table when a laptop is deleted; its snapshot remains in old_data.
CREATE TABLE IF NOT EXISTS public.laptop_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    laptop_id BIGINT,
    user_id BIGINT,
    operation VARCHAR(10) NOT NULL
        CHECK (operation IN ('INSERT', 'UPDATE', 'DELETE')),
    old_data JSONB,
    new_data JSONB,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE public.laptop_logs ADD COLUMN IF NOT EXISTS user_id BIGINT;
ALTER TABLE public.laptop_logs ALTER COLUMN laptop_id DROP NOT NULL;

-- Keep any legacy references that cannot be validated before adding the foreign keys.
UPDATE public.laptop_logs AS log
SET old_data = CASE
        WHEN jsonb_typeof(log.old_data) = 'object' THEN
            log.old_data || jsonb_build_object('_migration_orphaned_laptop_id', log.laptop_id)
        ELSE jsonb_build_object(
            '_previous_old_data', log.old_data,
            '_migration_orphaned_laptop_id', log.laptop_id
        )
    END,
    laptop_id = NULL
WHERE log.laptop_id IS NOT NULL
  AND NOT EXISTS (
      SELECT 1 FROM public.laptops AS laptop WHERE laptop.id = log.laptop_id
  );

UPDATE public.laptop_logs AS log
SET old_data = CASE
        WHEN jsonb_typeof(log.old_data) = 'object' THEN
            log.old_data || jsonb_build_object('_migration_orphaned_user_id', log.user_id)
        ELSE jsonb_build_object(
            '_previous_old_data', log.old_data,
            '_migration_orphaned_user_id', log.user_id
        )
    END,
    user_id = NULL
WHERE log.user_id IS NOT NULL
  AND NOT EXISTS (
      SELECT 1 FROM public.users AS app_user WHERE app_user.id = log.user_id
  );

DO $migration$
DECLARE
    existing_fk RECORD;
BEGIN
    FOR existing_fk IN
        SELECT conname
        FROM pg_constraint
        WHERE conrelid = 'public.laptop_logs'::regclass
          AND contype = 'f'
          AND confrelid IN ('public.laptops'::regclass, 'public.users'::regclass)
    LOOP
        EXECUTE format(
            'ALTER TABLE public.laptop_logs DROP CONSTRAINT %I',
            existing_fk.conname
        );
    END LOOP;
END;
$migration$;

ALTER TABLE public.laptop_logs
    ADD CONSTRAINT laptop_logs_laptop_id_fkey
    FOREIGN KEY (laptop_id) REFERENCES public.laptops(id)
    ON DELETE SET NULL NOT VALID;

ALTER TABLE public.laptop_logs
    VALIDATE CONSTRAINT laptop_logs_laptop_id_fkey;

ALTER TABLE public.laptop_logs
    ADD CONSTRAINT laptop_logs_user_id_fkey
    FOREIGN KEY (user_id) REFERENCES public.users(id)
    ON DELETE SET NULL NOT VALID;

ALTER TABLE public.laptop_logs
    VALIDATE CONSTRAINT laptop_logs_user_id_fkey;

CREATE INDEX IF NOT EXISTS laptop_logs_laptop_id_idx
    ON public.laptop_logs (laptop_id);

CREATE INDEX IF NOT EXISTS laptop_logs_user_id_idx
    ON public.laptop_logs (user_id);

CREATE OR REPLACE FUNCTION public.capture_laptop_log()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
DECLARE
    actor_id BIGINT;
    actor_setting TEXT;
BEGIN
    actor_setting := NULLIF(current_setting('rizzshop.user_id', true), '');
    IF actor_setting IS NOT NULL THEN
        actor_id := actor_setting::BIGINT;
    END IF;

    IF TG_OP = 'INSERT' THEN
        INSERT INTO public.laptop_logs (
            laptop_id, user_id, operation, old_data, new_data
        ) VALUES (
            NEW.id, actor_id, TG_OP, NULL, to_jsonb(NEW)
        );
        RETURN NEW;
    ELSIF TG_OP = 'UPDATE' THEN
        INSERT INTO public.laptop_logs (
            laptop_id, user_id, operation, old_data, new_data
        ) VALUES (
            NEW.id, actor_id, TG_OP, to_jsonb(OLD), to_jsonb(NEW)
        );
        RETURN NEW;
    ELSE
        -- A DELETE log uses a NULL FK so it survives deletion of its laptop.
        INSERT INTO public.laptop_logs (
            laptop_id, user_id, operation, old_data, new_data
        ) VALUES (
            NULL, actor_id, TG_OP, to_jsonb(OLD), NULL
        );
        RETURN OLD;
    END IF;
END;
$function$;

DROP TRIGGER IF EXISTS laptops_capture_audit_log ON public.laptops;

CREATE TRIGGER laptops_capture_audit_log
AFTER INSERT OR UPDATE OR DELETE ON public.laptops
FOR EACH ROW EXECUTE FUNCTION public.capture_laptop_log();
